def format_release(release: Release) -> str:
    """Готовый HTML-текст сообщения «Что нового» для отправки в Telegram."""
    header = (
        f"✨ <b>Что нового — {release.title}</b>\n"
        f"<i>Обновление от {release.date}</i>\n\n"
    )
    body = "\n".join(release.items)
    footer = "\n\nОткрывайте приложение и пробуйте 👇"
    return header + body + footer
