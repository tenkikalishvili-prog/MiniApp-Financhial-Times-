"""История обновлений для рассылки пользователям («Что нового»).

Единый источник правды для владельческой команды /announce. Чтобы объявить
новый релиз пользователям:
    1. добавь запись в начало RELEASES (самый свежий — первый);
    2. в боте выполни /announce (предпросмотр) → /announce confirm (рассылка).
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Release:
    """Один релиз: дата, заголовок и список пунктов «что нового» (уже с эмодзи)."""

    date: str  # человекочитаемая дата, напр. «31 августа»
    title: str  # короткий заголовок релиза
    items: list[str]  # пункты обзора обновления


# Самый свежий релиз — первым. LATEST всегда указывает на него.
RELEASES: list[Release] = [
    Release(
        date="31 августа",
        title="Бюджеты, категории и умный ввод",
        items=[
            "🧠 Умный ввод в боте: пишите свободным текстом — например «кофе 350» — "
            "и бот сам заведёт операцию.",
            "🗂 Категории: теперь можно создавать и удалять свои категории и "
            "подкатегории прямо в приложении.",
            "✏️ Переименование: тап по заголовку категории — и меняете название.",
            "📊 Бюджет по всем категориям: удобная карусель с правкой лимита и названия.",
            "⏰ Настройки уведомлений: включайте/выключайте утренний лимит и вечерние "
            "итоги, задавайте своё время и часовой пояс.",
            "🚀 Лёгкий онбординг при первом входе: доход и общий лимит трат за пару шагов.",
            "🎨 Обновлённый дизайн приложения: новая палитра, типографика и ключевые экраны.",
        ],
    ),
]

LATEST: Release = RELEASES[0]


def format_release(release: Release) -> str:
    """Готовый HTML-текст сообщения «Что нового» для отправки в Telegram."""
    header = (
        f"✨ <b>Что нового — {release.title}</b>\n"
        f"<i>Обновление от {release.date}</i>\n\n"
    )
    body = "\n".join(release.items)
    footer = "\n\nОткрывайте приложение и пробуйте 👇"
    return header + body + footer
